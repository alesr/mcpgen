// Command docgen generates the reference pages of the mcpgen documentation
// site from the real sources of truth, so the reference cannot drift:
//
//   - reference/generated/cli.mdx               from cli.BuildSchemaDoc (the
//     same document `mcpgen schema` emits — chosen because it is a single
//     source of truth shared with the CLI itself),
//   - reference/generated/config.mdx            from internal/config/schema.json,
//   - reference/generated/machine-interface.mdx exit/error codes parsed from
//     internal/cli/exit.go with go/parser, envelope from BuildSchemaDoc,
//   - reference/generated/project-files.mdx     from a real dry-run generation
//     (ops.New with DryRun) plus the check stages parsed from
//     internal/checks/checks.go.
//
// docgen fails if it finds a constant or stage it has no description for, so
// new exit codes, error codes, or check stages break the docs build until they
// are documented. Run from the repository root: `go run ./tools/docgen`.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/alesr/mcpgen/internal/app"
	"github.com/alesr/mcpgen/internal/cli"
	"github.com/alesr/mcpgen/internal/config"
	"github.com/alesr/mcpgen/internal/generator"
	"github.com/alesr/mcpgen/internal/ops"
)

const generatedNote = "{/* Generated by `go run ./tools/docgen`. Do not edit by hand; edit the source and run `make docs-gen`. */}"

// Internal links in generated pages carry the docs base path (`/mcpgen`,
// matching `base` in docs/astro.config.mjs): Starlight prefixes sidebar and
// hero links with base itself, but links inside MDX content must include it
// explicitly or the build output is broken on GitHub Pages and
// starlight-links-validator rejects them.
const linkBase = "/mcpgen"

func main() {
	root := flag.String("root", ".", "repository root")
	out := flag.String("out", "docs/src/content/docs/reference/generated", "output directory for generated MDX pages")
	flag.Parse()

	if err := run(*root, *out); err != nil {
		fmt.Fprintf(os.Stderr, "docgen: %v\n", err)
		os.Exit(1)
	}
}

func run(root, outDir string) error {
	schemaDoc, err := cli.BuildSchemaDoc(app.Version)
	if err != nil {
		return fmt.Errorf("build schema doc: %w", err)
	}

	pages := map[string][]byte{}
	pages["cli.mdx"] = cliPage(schemaDoc)
	pages["config.mdx"], err = configPage()
	if err != nil {
		return err
	}
	pages["machine-interface.mdx"], err = machineInterfacePage(root, schemaDoc)
	if err != nil {
		return err
	}
	pages["project-files.mdx"], err = projectFilesPage(root)
	if err != nil {
		return err
	}

	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	names := make([]string, 0, len(pages))
	for name := range pages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		path := filepath.Join(outDir, name)
		if err := os.WriteFile(path, pages[name], 0o644); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
		fmt.Printf("wrote %s\n", path)
	}
	return nil
}

