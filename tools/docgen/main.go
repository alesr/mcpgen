// writeSchemaObject renders a section per object schema property.
func writeSchemaObject(b *bytes.Buffer, schema map[string]any, prefix string, depth int) {
	props, _ := schema["properties"].(map[string]any)
	required, _ := schema["required"].([]any)
	reqSet := map[string]bool{}
	for _, r := range required {
		if s, ok := r.(string); ok {
			reqSet[s] = true
		}
	}
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	heading := strings.Repeat("#", depth)
	if prefix != "" {
		fmt.Fprintf(b, "%s `%s`\n\n", heading, prefix)
		if desc, _ := schema["description"].(string); desc != "" {
			fmt.Fprintf(b, "%s\n\n", desc)
		}
	}
	if len(keys) > 0 {
		fmt.Fprintf(b, "| Field | Type | Required | Constraints | Default | Description |\n")
		fmt.Fprintf(b, "|---|---|---|---|---|---|\n")
		for _, k := range keys {
			p, _ := props[k].(map[string]any)
			field := k
			if prefix != "" {
				field = prefix + "." + k
			}
			req := ""
			if reqSet[k] {
				req = "yes"
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s |\n",
				field, schemaType(p), req, schemaConstraints(p), schemaDefault(p), mdEscape(schemaDesc(p)))
		}
		fmt.Fprintf(b, "\n")
	}

	// Recurse into nested objects and array item objects.
	for _, k := range keys {
		p, _ := props[k].(map[string]any)
		child := k
		if prefix != "" {
			child = prefix + "." + k
		}
		if ref, _ := p["$ref"].(string); ref != "" && strings.HasPrefix(ref, "#/definitions/") {
			name := strings.TrimPrefix(ref, "#/definitions/")
			d, ok := schema["definitions"].(map[string]any)[name].(map[string]any)
			if !ok {
				continue
			}
			writeSchemaObject(b, d, child, depth+1)
			continue
		}
		if items, ok := p["items"].(map[string]any); ok {
			if ref, _ := items["$ref"].(string); ref != "" && strings.HasPrefix(ref, "#/definitions/") {
				name := strings.TrimPrefix(ref, "#/definitions/")
				d, ok := schema["definitions"].(map[string]any)[name].(map[string]any)
				if !ok {
					continue
				}
				writeSchemaObject(b, d, child+"[]", depth+1)
				continue
			}
			if items["type"] == "object" {
				if _, hasProps := items["properties"]; hasProps {
					writeSchemaObject(b, items, child+"[]", depth+1)
				}
				continue
			}
		}
		if p["type"] == "object" {
			if _, hasProps := p["properties"]; hasProps {
				writeSchemaObject(b, p, child, depth+1)
			}
		}
	}
}

func schemaType(p map[string]any) string {
	if t, ok := p["type"].(string); ok {
		return t
	}
	if _, ok := p["$ref"]; ok {
		return "object"
	}
	if _, ok := p["enum"]; ok {
		return "string"
	}
	if _, ok := p["const"]; ok {
		return "constant"
	}
	return "any"
}

func schemaConstraints(p map[string]any) string {
	var parts []string
	if c, ok := p["const"]; ok {
		parts = append(parts, fmt.Sprintf("must be `%v`", c))
	}
	if e, ok := p["enum"].([]any); ok {
		var vals []string
		for _, v := range e {
			vals = append(vals, fmt.Sprintf("`%v`", v))
		}
		parts = append(parts, "one of "+strings.Join(vals, ", "))
	}
	if s, ok := p["pattern"].(string); ok {
		parts = append(parts, "pattern `"+s+"`")
	}
	if s, ok := p["minLength"].(float64); ok {
		parts = append(parts, fmt.Sprintf("min length %d", int(s)))
	}
	if s, ok := p["minimum"].(float64); ok {
		parts = append(parts, fmt.Sprintf("min %d", int(s)))
	}
	if s, ok := p["maximum"].(float64); ok {
		parts = append(parts, fmt.Sprintf("max %d", int(s)))
	}
	return strings.Join(parts, "; ")
}

func schemaDefault(p map[string]any) string {
	if d, ok := p["default"]; ok {
		return fmt.Sprintf("`%v`", d)
	}
	return "—"
}

func schemaDesc(p map[string]any) string {
	d, _ := p["description"].(string)
	return d
}

